// Load harness: N synthetic attendees + 1 host against app instances that use
// the Graph simulator. Mirrors the browser's request pattern for the version
// under test (poll intervals are parameters). Isolated; never production.
//
//   node loadtest/harness.mjs --users 100 --exam-min 10 --bases http://127.0.0.1:4701,http://127.0.0.1:4702
import { createHash, randomUUID } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const arg = (name, dflt) => {
  const i = process.argv.indexOf("--" + name);
  return i > 0 ? process.argv[i + 1] : dflt;
};
const USERS = Number(arg("users", 10));
const EXAM_MIN = Number(arg("exam-min", 10));
const JOIN_WINDOW_S = Number(arg("join-window", 60));
const SUBMIT_WINDOW_S = Number(arg("submit-window", 90));
const ROOM_POLL_S = Number(arg("room-poll", 30));
const DASH_POLL_S = Number(arg("dash-poll", 60));
const HOST_POLL_S = Number(arg("host-poll", 60));
const BASES = arg("bases", "http://127.0.0.1:4701").split(",");
const SIM = `http://127.0.0.1:${arg("sim-port", 4600)}`;
const ORIGIN = arg("origin", "https://loadtest.example");
const OUT = arg("out", "loadtest-result.json");
const LABEL = arg("label", "run");
const UPLOADS = arg("uploads", "on") === "on";
const TIMEOUT_MS = 300000; // Vercel function limit; browsers would see a failure
const TASKS = ["inbox", "tables", "clean", "dashboard", "mbr"];
const T0 = Date.now();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const sha = (b) => createHash("sha256").update(b).digest("hex");

// ---------- measurement ----------
const samples = []; // {ep, status, ms, t}
const events = { saveFailures: 0, saveConflicts: 0, saveRetries: 0, selectRetries: 0, selectFailures: 0, uploadRetries: 0, uploadFailures: 0, submitFailures: 0, loginFailures: 0, joinFailures: 0, pollFailures: 0, hostPollFailures: 0 };
const norm = (p) => p.replace(/\/api\//, "").replace(/[a-f0-9]{20}-(pre|post)/, ":room").replace(/evidence\/[A-Za-z0-9_-]+/, "evidence/:id").replace(/\?.*$/, "");
let rr = 0;
async function call(user, method, path, body, { base } = {}) {
  const b = base || BASES[rr++ % BASES.length];
  const t = Date.now();
  let status = 0, data = null, text = "";
  try {
    const r = await fetch(b + path, {
      method,
      headers: { Origin: ORIGIN, "Content-Type": "application/json", ...(user?.cookie ? { Cookie: user.cookie } : {}) },
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    status = r.status;
    const sc = r.headers.get("set-cookie");
    if (sc && user && /te_session=/.test(sc)) user.cookie = sc.split(";")[0];
    text = await r.text();
    try { data = JSON.parse(text); } catch { data = null; }
  } catch (e) {
    status = e.name === "TimeoutError" ? 504 : 599;
  }
  samples.push({ ep: method + " " + norm(path), status, ms: Date.now() - t, t: t - T0 });
  return { status, data, ok: status >= 200 && status < 300, error: data?.error || text.slice(0, 120) };
}
async function sim(path, init) {
  return fetch(SIM + path, init);
}

// ---------- identity ----------
async function login(user, name, email) {
  for (let attempt = 0; attempt < 6; attempt++) {
    const r = await call(user, "POST", "/api/auth/request-code", { name, email });
    if (!r.ok) { await sleep(5000 + Math.random() * 5000); continue; }
    let code = null;
    for (let i = 0; i < 20 && !code; i++) { code = (await (await sim("/__mail?email=" + encodeURIComponent(email))).json()).code; if (!code) await sleep(250); }
    const v = await call(user, "POST", "/api/auth/verify-code", { challengeId: r.data.challengeId, code });
    if (v.ok && user.cookie) {
      user.verified = v.data?.id ? v.data : v.data?.identity || null;
      return true;
    }
    await sleep(5000);
  }
  events.loginFailures++;
  return false;
}

// ---------- attendee ----------
function pickThree() {
  const s = [...TASKS].sort(() => Math.random() - 0.5).slice(0, 3);
  return TASKS.filter((t) => s.includes(t));
}
// Genuine Office files (the app validates Office Open XML): 60% small,
// 35% 2-5 MB, 5% ~9.5 MB. Generated by loadtest/make-files.py.
const FILES = arg("files", "loadtest/files");
const pool = (re) => readdirSync(FILES).filter((f) => re.test(f));
const SMALL = { xlsx: pool(/^x[01]-/), pptx: pool(/^p0-/) };
const MEDIUM = { xlsx: pool(/^x[23]-/), pptx: pool(/^p[12]-/) };
const LARGE = { xlsx: pool(/^p3-/), pptx: pool(/^p3-/) };
const cacheFiles = new Map();
function makeFile(task, i) {
  const ext = task === "mbr" ? "pptx" : "xlsx";
  const r = Math.random();
  const set = (r < 0.6 ? SMALL : r < 0.95 ? MEDIUM : LARGE)[ext];
  const pick = set[Math.floor(Math.random() * set.length)];
  if (!cacheFiles.has(pick)) cacheFiles.set(pick, readFileSync(FILES + "/" + pick));
  const data = cacheFiles.get(pick);
  return { name: `${task}-evidence-${i}.${pick.split(".").pop()}`, data, sha256: sha(data) };
}

async function attendee(i, room, endAt) {
  const u = { i, email: `loadtest.user${String(i).padStart(3, "0")}@gmail.example`, cookie: "", result: { ok: false, issues: [] } };
  await sleep((i / USERS) * JOIN_WINDOW_S * 1000);
  if (!(await login(u, `Load Test ${i}`, u.email))) { u.result.issues.push("login"); return u; }
  // Identity comes from the verified sign-in; /me (retried) must agree with it.
  let me = await call(u, "GET", "/api/auth/me");
  for (let a = 0; a < 5 && !me.ok; a++) { await sleep(5000); me = await call(u, "GET", "/api/auth/me"); }
  u.id = u.verified?.id || me.data?.identity?.id;
  if (!u.id) { u.result.issues.push("no-identity"); return u; }
  if (me.ok && me.data?.identity?.id !== u.id) u.result.issues.push("me-mismatch");
  if (me.ok && me.data?.identity?.role !== "attendee") u.result.issues.push("role:" + me.data?.identity?.role);
  await call(u, "GET", "/api/dashboard");
  // join
  let joined = false;
  for (let a = 0; a < 6 && !joined; a++) {
    const v = await call(u, "GET", `/api/rooms/${room}/validate`);
    const j = v.ok && (await call(u, "POST", `/api/rooms/${room}/join`, {}));
    joined = !!(j && j.ok);
    if (!joined) await sleep(8000);
  }
  if (!joined) { events.joinFailures++; u.result.issues.push("join"); return u; }
  let detail = (await call(u, "GET", `/api/rooms/${room}`)).data;
  // select three (the button can be pressed again after an error)
  u.chosen = pickThree();
  let started = null;
  for (let a = 0; a < 8 && !started; a++) {
    const s = await call(u, "POST", `/api/rooms/${room}/start`, { selected: u.chosen });
    if (s.ok) started = s.data.participant;
    else {
      // Fixed client: re-read the record; continue if the selection was saved.
      const d = await call(u, "GET", `/api/rooms/${room}`);
      if (d.ok && d.data.participant?.selected?.length === 3) started = d.data.participant;
      else { events.selectRetries++; await sleep(8000); }
    }
  }
  if (!started) { events.selectFailures++; u.result.issues.push("select"); return u; }
  u.deadline = started.deadline;
  detail = (await call(u, "GET", `/api/rooms/${room}`)).data || detail;
  const p0 = detail?.participant || started;
  // ---- exam activity ----
  const draft = { answers: Object.fromEntries(u.chosen.map((t) => [t, [-1, -1, -1, -1]])), notes: Object.fromEntries(u.chosen.map((t) => [t, ""])), completed: [] };
  let revision = p0.revision, version = 0, savedVersion = 0, confirmed = null, saving = null, locked = false;
  const flush = async () => {
    if (saving) { await saving; if (savedVersion === version) return; }
    saving = (async () => {
      while (savedVersion < version && !locked) {
        const v = version, snap = structuredClone(draft);
        const r = await call(u, "POST", `/api/rooms/${room}/save`, { revision, ...snap });
        if (r.ok) { revision = r.data.participant.revision; savedVersion = v; confirmed = snap; }
        else if (r.status === 409 && /tab|revision|changed/i.test(r.error)) { events.saveConflicts++; u.result.issues.push("save-conflict:" + r.error); locked = true; }
        else if (/locked|closed/i.test(r.error)) { locked = true; }
        else { events.saveRetries++; await sleep(8000); }
      }
    })();
    try { await saving; } finally { saving = null; }
  };
  let pending = null;
  const edit = () => { version++; clearTimeout(pending); pending = setTimeout(() => void flush(), 1200); };
  const examMs = endAt - Date.now();
  const at = (frac) => Date.now() + frac * examMs;
  const plan = [];
  for (const t of u.chosen) {
    for (let q = 0; q < 4; q++) plan.push({ when: at(0.05 + Math.random() * 0.7), kind: "answer", t, q });
    for (let k = 0; k < 3; k++) plan.push({ when: at(0.05 + Math.random() * 0.75), kind: "notes", t });
    if (UPLOADS) plan.push({ when: at(0.2 + Math.random() * 0.55), kind: "upload", t });
  }
  plan.sort((a, b) => a.when - b.when);
  const uploaded = {};
  let poll = setInterval(async () => {
    if (locked) return;
    const r = await call(u, "GET", `/api/rooms/${room}`);
    if (!r.ok) events.pollFailures++;
  }, ROOM_POLL_S * 1000);
  for (const step of plan) {
    await sleep(Math.max(0, step.when - Date.now()));
    if (step.kind === "answer") { draft.answers[step.t][step.q] = Math.floor(Math.random() * 4); edit(); }
    if (step.kind === "notes") {
      for (let k = 0; k < 4; k++) { draft.notes[step.t] += `Note ${k} on ${step.t}. `; edit(); await sleep(400); }
    }
    if (step.kind === "upload") {
      await flush();
      const file = makeFile(step.t, i);
      const after = await upload(u, room, step.t, file);
      // Like the browser: adopt the record (and revision) the server returned.
      if (after) { uploaded[step.t] = file; revision = after.revision; }
    }
    // Mark complete when the server has evidence and 4 answers.
    for (const t of u.chosen)
      if (!draft.completed.includes(t) && (uploaded[t] || !UPLOADS) && draft.answers[t].every((x) => x >= 0)) { await flush(); draft.completed.push(t); edit(); }
  }
  // Submit inside the shared submission window.
  await sleep(Math.max(0, endAt - Date.now()) + Math.random() * SUBMIT_WINDOW_S * 1000);
  clearTimeout(pending);
  await flush();
  clearInterval(poll);
  let sub = null;
  for (let a = 0; a < 6 && !sub; a++) {
    const r = await call(u, "POST", `/api/rooms/${room}/submit`, {});
    if (r.ok) sub = r.data.participant;
    else if (r.status === 400) { (events.submitErrors ||= {})[String(r.error).slice(0, 100)] = 1; break; }
    else if (/locked|submitted/i.test(r.error)) { sub = (await call(u, "GET", `/api/rooms/${room}`)).data?.participant; }
    else await sleep(8000);
  }
  if (!sub) { events.submitFailures++; u.result.issues.push("submit"); return u; }
  const dup = await call(u, "POST", `/api/rooms/${room}/submit`, {}); // double click
  const fin = (await call(u, "GET", `/api/rooms/${room}`)).data?.participant;
  u.final = fin; u.confirmed = confirmed; u.uploaded = uploaded; u.firstSubmit = sub.submittedAt;
  // ---- integrity ----
  const iss = u.result.issues;
  if (!fin) iss.push("final-read");
  else {
    if (fin.identity.id !== u.id) iss.push("cross-user-record");
    if (JSON.stringify(fin.selected) !== JSON.stringify(u.chosen) || fin.selected.length !== 3) iss.push("selection");
    if (fin.deadline !== u.deadline) iss.push("deadline-changed");
    if (fin.submittedAt !== sub.submittedAt) iss.push("submittedAt-changed");
    if (dup.ok && dup.data?.participant?.submittedAt !== sub.submittedAt) iss.push("duplicate-submit-changed");
    if (confirmed)
      for (const t of u.chosen) {
        if (JSON.stringify(fin.answers[t] || []) !== JSON.stringify(confirmed.answers[t])) iss.push("answers-lost:" + t);
        if ((fin.notes[t] || "") !== confirmed.notes[t]) iss.push("notes-lost:" + t);
      }
    for (const [t, f] of Object.entries(uploaded)) {
      const e = fin.evidence.find((x) => x.task === t && x.sha256 === f.sha256);
      if (!e) iss.push("evidence-missing:" + t);
      else if (!e.path.includes(`/evidence/${u.id}/`)) iss.push("evidence-path:" + t);
    }
    if (fin.evidence.some((e) => !e.path.includes(`/evidence/${u.id}/`))) iss.push("foreign-evidence");
  }
  u.result.ok = iss.length === 0;
  return u;
}

async function upload(u, room, task, file) {
  for (let attempt = 0; attempt < 3; attempt++) {
    const s = await call(u, "POST", `/api/rooms/${room}/upload-start`, { task, name: file.name, size: file.data.length, sha256: file.sha256 });
    if (!s.ok) { events.uploadRetries++; await sleep(10000); continue; }
    let committed = s.data.committed, steps = 0, failed = false;
    const chunk = 10 * 320 * 1024;
    while (!committed && steps++ < 40) {
      const st = await call(u, "POST", `/api/rooms/${room}/upload-status`, { uploadId: s.data.uploadId });
      if (!st.ok) { failed = true; break; }
      if (st.data.committed) { committed = true; break; }
      const off = st.data.offset, end = Math.min(file.data.length, off + chunk);
      const url = new URL(s.data.uploadUrl);
      const t = Date.now();
      let status = 0;
      try {
        const r = await fetch(SIM + url.pathname, { method: "PUT", headers: { "x-sim-host": url.hostname, "Content-Range": `bytes ${off}-${end - 1}/${file.data.length}` }, body: file.data.subarray(off, end), signal: AbortSignal.timeout(TIMEOUT_MS) });
        status = r.status; await r.arrayBuffer();
        if (r.status === 429 || r.status === 503) await sleep(1000 * Number(r.headers.get("retry-after") || 2));
      } catch { status = 599; }
      samples.push({ ep: "PUT sharepoint-chunk", status, ms: Date.now() - t, t: t - T0 });
      if (status === 200 || status === 201) committed = true;
    }
    if (failed || !committed) { events.uploadRetries++; await sleep(10000); continue; }
    const c = await call(u, "POST", `/api/rooms/${room}/upload-complete`, { uploadId: s.data.uploadId });
    if (c.ok) return c.data.participant;
    (events.uploadErrors ||= {})[String(c.status) + " " + String(c.error).slice(0, 100)] = ((events.uploadErrors || {})[String(c.status) + " " + String(c.error).slice(0, 100)] || 0) + 1;
    events.uploadRetries++; await sleep(10000);
  }
  events.uploadFailures++;
  return null;
}

// ---------- host ----------
async function main() {
  await sim("/__put?path=" + encodeURIComponent(`${process.env.GRAPH_STORAGE_ROOT || "LoadTest"}/config/host-allowlist.json`), { method: "POST", body: JSON.stringify({ emails: ["host@loadtest.example"] }) });
  const host = { cookie: "" };
  if (!(await login(host, "Load Host", "host@loadtest.example"))) throw new Error("host login failed");
  const me = await call(host, "GET", "/api/auth/me");
  if (me.data?.identity?.role !== "host") throw new Error("host role missing");
  const prog = await call(host, "POST", "/api/programs", { company: "LoadTest Co", cohort: `${LABEL} ${USERS}u`, requestId: randomUUID() });
  const room = prog.data?.program?.preRoomId;
  if (!room) throw new Error("room creation failed: " + JSON.stringify(prog));
  const endAt = Date.now() + JOIN_WINDOW_S * 1000 + EXAM_MIN * 60000;
  let hostRunning = true;
  const hostLoop = (async () => {
    while (hostRunning) {
      const rooms = await call(host, "GET", "/api/rooms");
      if (!rooms.ok) events.hostPollFailures++;
      const p = await call(host, "GET", `/api/rooms/${room}/participants`);
      if (!p.ok) events.hostPollFailures++;
      await sleep(HOST_POLL_S * 1000);
    }
  })();
  const users = await Promise.all(Array.from({ length: USERS }, (_, i) => attendee(i + 1, room, endAt)));
  hostRunning = false;
  await hostLoop;
  // Host: evidence readback for every file, grading sample, Excel export.
  const roster = (await call(host, "GET", `/api/rooms/${room}/participants`)).data?.participants || [];
  let readbackOk = 0, readbackBad = 0;
  for (const u of users.filter((x) => x.final)) {
    for (const [t, f] of Object.entries(u.uploaded || {})) {
      const e = u.final.evidence.find((x) => x.task === t && x.sha256 === f.sha256);
      if (!e) continue;
      const link = await call(host, "GET", `/api/rooms/${room}/evidence/${e.id}?participant=${u.id}`);
      let good = false;
      if (link.ok && link.data?.downloadUrl) {
        const dl = new URL(link.data.downloadUrl);
        const r = await fetch(SIM + dl.pathname, { headers: { "x-sim-host": dl.hostname } });
        good = r.ok && sha(Buffer.from(await r.arrayBuffer())) === f.sha256;
      }
      if (good) readbackOk++; else { readbackBad++; u.result.issues.push("readback:" + t); u.result.ok = false; }
    }
  }
  for (const u of users.filter((x) => x.final).slice(0, 5))
    for (const t of u.chosen)
      await call(host, "POST", `/api/rooms/${room}/grade`, { participantId: u.id, task: t, expectedAt: null, quality: 2, accuracy: 3, completeness: 3, feedback: "Load test grading" });
  const ex = await call(host, "GET", `/api/rooms/${room}/export`);
  let excel = { ok: false };
  if (ex.ok && ex.data?.downloadUrl) {
    const dl = new URL(ex.data.downloadUrl);
    const buf = Buffer.from(await (await fetch(SIM + dl.pathname, { headers: { "x-sim-host": dl.hostname } })).arrayBuffer());
    const ExcelJS = createRequire(import.meta.url)("exceljs");
    const wb = new ExcelJS.Workbook();
    await wb.xlsx.load(buf);
    const sheet = wb.getWorksheet("Participants");
    excel = { ok: true, sheets: wb.worksheets.map((w) => w.name), participantRows: sheet ? sheet.rowCount - 1 : null };
  }
  // ---- report ----
  const byEp = {};
  for (const s of samples) (byEp[s.ep] ||= []).push(s);
  const pct = (a, q) => a[Math.min(a.length - 1, Math.floor(a.length * q))];
  const endpoints = Object.fromEntries(Object.entries(byEp).sort().map(([ep, xs]) => {
    const ms = xs.map((x) => x.ms).sort((a, b) => a - b);
    const fails = xs.filter((x) => x.status >= 500 || x.status === 0 || x.status === 599).length;
    const codes = {}; for (const x of xs) codes[x.status] = (codes[x.status] || 0) + 1;
    return [ep, { n: xs.length, failed: fails, failRate: +(fails / xs.length * 100).toFixed(2), p50: pct(ms, 0.5), p95: pct(ms, 0.95), p99: pct(ms, 0.99), max: ms.at(-1), codes }];
  }));
  const simStats = await (await sim("/__stats")).json();
  const allApi = samples.filter((s) => !s.ep.startsWith("PUT sharepoint"));
  const apiMs = allApi.map((s) => s.ms).sort((a, b) => a - b);
  const issues = {};
  for (const u of users) for (const x of u.result.issues) { const k = x.split(":")[0]; issues[k] = (issues[k] || 0) + 1; }
  const report = {
    label: LABEL, users: USERS, examMin: EXAM_MIN, instances: BASES.length, polls: { room: ROOM_POLL_S, dashboard: DASH_POLL_S, host: HOST_POLL_S },
    durationS: Math.round((Date.now() - T0) / 1000),
    completedWorkflow: users.filter((u) => u.result.ok).length,
    integrityIssues: issues,
    usersWithIssues: users.filter((u) => u.result.issues.length).map((u) => ({ user: u.i, issues: u.result.issues })).slice(0, 50),
    events,
    api: { n: allApi.length, failed: allApi.filter((s) => s.status >= 500 || s.status === 599).length, p50: pct(apiMs, 0.5), p95: pct(apiMs, 0.95), p99: pct(apiMs, 0.99) },
    evidenceReadback: { ok: readbackOk, bad: readbackBad },
    roster: roster.length, excel,
    sharepoint: { ruTotal: simStats.ru, ruPerMinute: simStats.perMinute, throttled429: simStats.throttled, retryAfter: simStats.retryAfter, calls: simStats.calls, injected503: simStats.injected503, drops: simStats.drops },
    endpoints,
  };
  writeFileSync(OUT, JSON.stringify(report, null, 1));
  console.log(JSON.stringify({ label: LABEL, users: USERS, completed: report.completedWorkflow, issues, api: report.api, throttled429: simStats.throttled, ruPeakMin: Math.max(...Object.values(simStats.perMinute)), readback: report.evidenceReadback, excel, events }));
}
main().catch((e) => { console.error("HARNESS FAILED", e); process.exit(1); });
